function base(partial = {}) {
  return {
    billDate: todayStr(),
    createdAt: `${todayStr()} 09:15:00`,
    updatedAt: `${todayStr()} 09:15:00`,
    enable: 1,
    priority: 10,
    remark: '',
    status: '正常',
    ...partial,
  }
}

function filterBy(keys) {
  return (rows, p) => {
    let next = rows
    for (const key of keys) {
      if (p[key] !== undefined && p[key] !== null && p[key] !== '') {
        next = next.filter((r) =>
          String(r[key] ?? '').includes(String(p[key]).trim()),
        )
      }
    }
    return next
  }
}

